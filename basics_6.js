
//push(), pop(), unshift() methods 

let marks = [20, 40, 35, 14, 37, 100]
 
// Add element at end
marks.push(65)
 
console.log(marks) //output [20,40,35,14,37,100,65]
 

 
 
// Remove last element
marks.pop()
 
console.log(marks) //output [20,40,35,14,37,100]

 
 
// Add element at beginning
marks.unshift(12);
 
console.log(marks) // output [12,20,40,35,14,37,100]
 
